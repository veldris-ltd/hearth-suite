// Generate CSS custom properties from the token source of truth (AC-DS-1).
//
// Emits dist/tokens.css and a copy of dist/tokens.json. The CSS carries:
//   - theme-agnostic vars on :root (type, spacing, radius, stroke, motion,
//     layout, sizes) plus the primitive colour ramps (--hb-<ramp>-<stop>);
//   - the light semantic/module/elevation/chart layer on :root;
//   - the dark layer via [data-theme="dark"] and prefers-color-scheme.
// Run with `node`.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const tokens = JSON.parse(readFileSync(join(root, "src", "tokens.json"), "utf8"));

/** Theme-agnostic declarations (type, spacing, motion, layout, …). */
function staticVars() {
  const lines = [];
  const push = (name, value) => lines.push(`  ${name}: ${value};`);

  push("--hb-font-serif", tokens.type["font-serif"]);
  push("--hb-font-sans", tokens.type["font-sans"]);
  push("--hb-font-mono", tokens.type["font-mono"]);
  // Named type scale (v1.0): each step carries a size, line-height and optional
  // letter-spacing. The serif/sans/mono family per step is documented; headings
  // (display/h1/h2 serif, h3/h4 sans) and code (mono) set it where they apply.
  for (const [step, s] of Object.entries(tokens.type.scale)) {
    push(`--hb-text-${step}`, s.size);
    push(`--hb-leading-${step}`, s.line);
    if (s.tracking) push(`--hb-tracking-${step}`, s.tracking);
  }
  for (const [k, v] of Object.entries(tokens.type.weight)) push(`--hb-weight-${k}`, v);
  for (const [k, v] of Object.entries(tokens.type.leading)) push(`--hb-leading-${k}`, v);
  for (const [k, v] of Object.entries(tokens.space)) push(`--hb-space-${k}`, v);
  for (const [k, v] of Object.entries(tokens.radius)) push(`--hb-radius-${k}`, v);
  for (const [k, v] of Object.entries(tokens.stroke)) push(`--hb-stroke-${k}`, v);
  for (const [k, v] of Object.entries(tokens.size)) push(`--hb-size-${k}`, v);
  for (const [k, v] of Object.entries(tokens.motion.duration)) push(`--hb-dur-${k}`, v);
  for (const [k, v] of Object.entries(tokens.motion.easing)) push(`--hb-ease-${k}`, v);
  for (const [k, v] of Object.entries(tokens.layout)) push(`--hb-${k}`, v);
  return lines.join("\n");
}

/** Primitive colour ramps, raw values, no `color` segment (--hb-ember-500). */
function rampVars() {
  const lines = [];
  for (const [ramp, stops] of Object.entries(tokens.ramp)) {
    for (const [stop, v] of Object.entries(stops)) lines.push(`  --hb-${ramp}-${stop}: ${v};`);
  }
  return lines.join("\n");
}

/** Per-theme colour, module, elevation and chart declarations. */
function themeVars(theme) {
  const lines = [];
  for (const [k, v] of Object.entries(tokens.semantic[theme]))
    lines.push(`  --hb-color-${k}: ${v};`);
  for (const [k, v] of Object.entries(tokens.module[theme])) lines.push(`  --hb-color-${k}: ${v};`);
  for (const [k, v] of Object.entries(tokens.elevation[theme]))
    lines.push(`  --hb-elev-${k}: ${v};`);
  (tokens.chart?.[theme] ?? []).forEach((v, i) => lines.push(`  --hb-chart-${i + 1}: ${v};`));
  return lines.join("\n");
}

const css = `/* Generated by scripts/build.mjs from src/tokens.json. Do not edit by hand. */

:root {
${staticVars()}

  /* Primitive colour ramps */
${rampVars()}

  /* Light theme (default) */
${themeVars("light")}
}

[data-theme="dark"] {
${themeVars("dark")}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${themeVars("dark")}
  }
}

/* Honour the OS "reduce motion" preference globally (v1.0): neutralise every
   animation and transition. Components reference --hb-dur-* and --hb-ease-* so they
   animate calmly by default and not at all here. */
@media (prefers-reduced-motion: reduce) {
  *,
  *::before,
  *::after {
    animation-duration: 0.001ms !important;
    animation-iteration-count: 1 !important;
    transition-duration: 0.001ms !important;
    scroll-behavior: auto !important;
  }
}
`;

mkdirSync(join(root, "dist"), { recursive: true });
writeFileSync(join(root, "dist", "tokens.css"), css);
writeFileSync(join(root, "dist", "tokens.json"), `${JSON.stringify(tokens, null, 2)}\n`);
console.log("Wrote dist/tokens.css and dist/tokens.json");
